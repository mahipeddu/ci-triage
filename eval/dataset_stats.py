"""Dataset, label, teacher-data and training statistics from the local (gitignored) data -> eval/dataset_stats.md,
so the README only cites committed numbers.

Usage: python -m eval.dataset_stats
"""
import argparse
import json
from collections import Counter
from pathlib import Path

from collect.github_logs import ROOT

P = ROOT / "data/processed"
LABELS = ["flaky", "infra", "regression_strong", "regression_weak"]
UNLABELED = ["too_recent", "aggregator", "api_error"]


def jsonl(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.open()]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=ROOT / "eval/dataset_stats.md")
    ap.add_argument("--before-infra-fix", type=Path, default=P / "failures_labeled.before_infra_fix.jsonl")
    args = ap.parse_args()

    recs = jsonl(P / "failures_labeled.jsonl")
    repos = sorted({r["repo"] for r in recs}, key=lambda x: -sum(r["repo"] == x for r in recs))
    lines = ["# Dataset statistics", "", "Generated by `python -m eval.dataset_stats` from `data/processed/` (gitignored).",
             "", "## Failed jobs collected and auto-labels (job level)", "",
             "| repo | failed jobs | flaky | infra | regression strong | regression weak | unlabeled: too recent "
             "| unlabeled: aggregator | unlabeled: no rule fired | first job | last job |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for repo in repos + ["all"]:
        rs = [r for r in recs if repo in ("all", r["repo"])]
        lab = Counter(r["label"] for r in rs)
        src = Counter(r["label_source"] for r in rs if r["label"] is None)
        other = sum(n for s, n in src.items() if s not in ("too_recent", "aggregator"))
        t = sorted(r["job_started_at"] for r in rs)
        lines.append(f"| {repo} | {len(rs)} | " + " | ".join(str(lab[l]) for l in LABELS)
                     + f" | {src['too_recent']} | {src['aggregator']} | {other} | {t[0][:10]} | {t[-1][:10]} |")
    lines += ["", "Flaky by source: " + ", ".join(f"{k} {v}" for k, v in
                                                Counter(r["label_source"] for r in recs if r["label"] == "flaky").items()),
              "", "pytorch side sources: " + ", ".join(f"{n} {len(jsonl(P / f))}" for n, f in (
                  ("DISABLED issues", "pytorch_disabled.jsonl"), ("inner-flaky test records", "pytorch_inner_flaky.jsonl"),
                  ("per-test failure records", "pytorch_test_failures.jsonl"))) + ".", ""]

    if args.before_infra_fix.exists():
        old = {r["job_id"]: r for r in jsonl(args.before_infra_fix)}
        pairs = [(old[r["job_id"]], r) for r in recs if r["job_id"] in old]
        lost = Counter((a["infra_match"] or {}).get("pattern") for a, b in pairs if a["infra_match"] and not b["infra_match"])
        gained = Counter((b["infra_match"] or {}).get("pattern") for a, b in pairs if b["infra_match"] and not a["infra_match"])
        changed = Counter((a["label"], b["label"]) for a, b in pairs if a["label"] != b["label"])
        lines += ["## Infra pattern fix (substring bug)", "",
                  "Before the fix, patterns matched inside other words (e.g. `ENOTFOUND` inside `ModuleNotFoundError`). "
                  "After: word boundaries, case-sensitive error codes.", "",
                  f"- infra pattern matches removed: {sum(lost.values())} jobs ("
                  + ", ".join(f"{k} {v}" for k, v in lost.most_common()) + ")",
                  f"- infra pattern matches added: {sum(gained.values())} jobs ("
                  + ", ".join(f"{k} {v}" for k, v in gained.most_common()) + ")",
                  f"- final labels changed: {sum(changed.values())} jobs ("
                  + ", ".join(f"{a} → {b} {n}" for (a, b), n in changed.most_common()) + ")", ""]

    teacher = jsonl(P / "teacher_train.jsonl")
    rat = jsonl(P / "teacher_rationalized.jsonl")
    lines += ["## Teacher data (gemini-3.5-flash-lite, prompt v1, train incidents)", "",
              "Kept = teacher category equals the auto-label (used to train the rationale student).", "",
              "| auto-label | train incidents | kept | dropped | rationalized (label given to teacher) |",
              "|---|---|---|---|---|"]
    for c in ("flaky", "infra", "regression"):
        ts = [r for r in teacher if r["label"] == c]
        rs = [r for r in rat if r["label"] == c]
        lines.append(f"| {c} | {len(ts)} | {sum(r['match'] for r in ts)} | {sum(not r['match'] for r in ts)} "
                     f"| {sum(r['match'] and bool(r['likely_cause']) for r in rs)} of {len(rs)} |" if rs else
                     f"| {c} | {len(ts)} | {sum(r['match'] for r in ts)} | {sum(not r['match'] for r in ts)} | – |")
    lines += ["", "## Student training (Qwen3-4B-Instruct-2507, QLoRA 4-bit, RTX 5080)", "",
              "| student | train examples | sources | steps (early stopping) | best val loss | wall time | peak VRAM allocated |",
              "|---|---|---|---|---|---|---|"]
    for name in ("student_labels", "student_rationale", "student_rationale_rationalized"):
        f = ROOT / f"data/models/{name}/train_log.json"
        if f.exists():
            d = json.loads(f.read_text())
            src = ", ".join(f"{k} {v}" for k, v in d["teacher_sources"].items() if k != "null" and k)
            lines.append(f"| {name.removeprefix('student_')} | {d['train_examples']} (oversampled to "
                         f"{d['train_oversampled']}) | {src or 'auto-labels'} | {d['steps']} | {d['best_eval_loss']:.3f} "
                         f"| {d['wall_seconds'] / 60:.1f} min | {d['peak_vram_allocated_gb']} GB |")
    ledger = ROOT / "data/raw/gemini_spend.jsonl"
    if ledger.exists():
        rs = [r for r in jsonl(ledger) if r["model"] == "gemini-3.8-flash"]
        tin, tout = sum(r["in"] for r in rs), sum(r["out"] + r["thoughts"] for r in rs)
        lines += ["", "## gemini-3.8-flash spend (paid tier, from the token ledger)", "",
                  f"{len(rs)} billed responses, {tin} input + {tout} output tokens = "
                  f"${(tin * 0.75 + tout * 3.75) / 1e6:.2f} at $0.75/M in, $3.75/M out."]
    args.out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
